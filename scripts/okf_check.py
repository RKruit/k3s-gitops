#!/usr/bin/env python3
"""OKF-light docs validator — homelab docs as structured, self-checked markdown.

Convention (the ``docs/`` tree is "OKF-light", no external gem):

- every page under ``docs/`` starts with YAML frontmatter::

      description: one-liner stating what the page is for (no |, no newline)
      related:     optional list of docs-root-relative paths to other pages

- ``docs/index.md`` carries the generated overview between
  ``<!-- okf:index:start -->`` and ``<!-- okf:index:end -->``.

Checks:
  1. every docs page has sane frontmatter (description present, related targets exist)
  2. every internal ``*.md`` link in every page resolves (mkdocs --strict safety)
  3. every docs page is in ``mkdocs.yml`` nav; every nav entry has a page
  4. the generated index section on index.md is fresh (else: stale → regenerate)

Usage (from repo root, via the mkdocs venv so PyYAML is present):

    ~/.hermes/venvs/mkdocs/bin/python3 scripts/okf_check.py [--write-index]

``--write-index`` regenerates the index section in docs/index.md, then re-checks.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
FM_RE = re.compile(r"\A---\n(.*?\n)---\n", re.DOTALL)
MD_LINK = re.compile(r"\[[^\]\n]*\]\(([^()\s]+)\)")
MARK_START = "<!-- okf:index:start -->"
MARK_END = "<!-- okf:index:end -->"


def parse_nav() -> list[tuple[str, list[tuple[str, str]]]]:
    """Line-scan the nav block of mkdocs.yml.

    yaml.safe_load cannot read mkdocs.yml (the mermaid fence uses a
    ``!!python/name:`` tag), so parse nav by line shape instead.
    """
    text = (ROOT / "mkdocs.yml").read_text()
    nav: list[tuple[str, list[tuple[str, str]]]] = []
    in_nav = False
    for raw in text.splitlines():
        line = raw.rstrip()
        if line == "nav:":
            in_nav = True
            continue
        if not in_nav:
            continue
        if not line.startswith(" "):
            break
        m_top_page = re.match(r"^  - (.+?): (\S+\.md)$", line)
        m_section = re.match(r"^  - (.+?):$", line)
        m_entry = re.match(r"^      - (.+?): (\S+\.md)$", line)
        if m_top_page:
            nav.append(("Home", [(m_top_page.group(1), m_top_page.group(2))]))
        elif m_section:
            nav.append((m_section.group(1), []))
        elif m_entry and nav:
            nav[-1][1].append((m_entry.group(1), m_entry.group(2)))
    return nav


def load_page(path: Path) -> tuple[dict | None, str]:
    text = path.read_text()
    m = FM_RE.match(text)
    if not m:
        return None, text
    return yaml.safe_load(m.group(1)) or {}, text


def internal_md_targets(text: str):
    for match in MD_LINK.finditer(text):
        target = match.group(1)
        if target.startswith(("http://", "https://", "mailto:", "#")):
            continue
        target = target.split("#", 1)[0]
        if target:
            yield target


def build_index(nav: list[tuple[str, list[tuple[str, str]]]], fm_by_rel: dict[str, dict]) -> str:
    out = [
        "## Doc-index",
        "",
        "Every page carries frontmatter: a `description` one-liner plus an optional "
        "`related` list (paths relative to the `docs/` root). This section is "
        "regenerated by `scripts/okf_check.py --write-index`.",
        "",
    ]
    for section, entries in nav:
        if section == "Home" or not entries:
            continue
        out += [f"### {section}", "", "| Page | Description |", "|---|---|"]
        for title, rel in entries:
            desc = fm_by_rel.get(rel, {}).get("description") or "TODO: description missing"
            out.append(f"| [`{title}`]({rel}) | {desc} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    write_index = "--write-index" in argv
    problems: list[str] = []

    pages = sorted(DOCS.rglob("*.md"), key=lambda p: str(p))
    nav = parse_nav()
    if not nav:
        problems.append("mkdocs.yml: nav could not be parsed by okf_check")

    fm_by_rel: dict[str, dict] = {}
    for page in pages:
        rel = str(page.relative_to(DOCS))
        fm, body = load_page(page)
        if fm is None:
            problems.append(f"{rel}: no YAML frontmatter at the top")
            fm_by_rel[rel] = {}
            continue
        desc = fm.get("description")
        if not isinstance(desc, str) or not desc.strip():
            problems.append(f"{rel}: 'description' missing or empty")
        elif "|" in desc or "\n" in desc:
            problems.append(f"{rel}: 'description' must be one line without '|'")
        fm["description"] = (desc or "").strip()
        fm_by_rel[rel] = fm

        related = fm.get("related", [])
        if related is None or related == {}:
            related = []
        if not isinstance(related, list):
            problems.append(f"{rel}: 'related' must be a list")
            related = []
        seen: set[str] = set()
        for entry in related:
            if not isinstance(entry, str):
                problems.append(f"{rel}: non-string related entry {entry!r}")
                continue
            if entry == rel:
                problems.append(f"{rel}: related points to itself ({entry})")
            if entry in seen:
                problems.append(f"{rel}: duplicate related entry {entry}")
            seen.add(entry)
            target = (DOCS / entry).resolve()
            if not target.is_file():
                problems.append(f"{rel}: related path does not exist: {entry}")
            elif DOCS.resolve() not in target.parents:
                problems.append(f"{rel}: related path leaves docs/: {entry}")

        for target in internal_md_targets(body):
            if not target.endswith(".md"):
                continue
            resolved = (page.parent / target).resolve()
            if not resolved.is_file() or DOCS.resolve() not in resolved.parents:
                problems.append(f"{rel}: broken internal link: {target}")

    nav_paths = {rel for _section, entries in nav for _title, rel in entries}
    page_rels = {str(p.relative_to(DOCS)) for p in pages}
    for orphan in sorted(page_rels - nav_paths):
        problems.append(f"{orphan}: page is not in mkdocs.yml nav")
    for dangling in sorted(nav_paths - page_rels):
        problems.append(f"{dangling}: nav entry has no page on disk")

    idx = DOCS / "index.md"
    idx_text = idx.read_text()
    gen = build_index(nav, fm_by_rel)
    if MARK_START in idx_text and MARK_END in idx_text:
        pre, rest = idx_text.split(MARK_START, 1)
        block, post = rest.split(MARK_END, 1)
        if block.strip("\n") != gen.strip("\n"):
            if write_index:
                idx.write_text(pre + MARK_START + "\n" + gen + "\n" + MARK_END + post)
                print("okf: index section regenerated in docs/index.md")
            else:
                problems.append(
                    "docs/index.md: generated index is stale "
                    "(run: scripts/okf_check.py --write-index)"
                )
    else:
        if write_index:
            idx.write_text(
                idx_text.rstrip("\n")
                + "\n\n"
                + MARK_START
                + "\n"
                + gen
                + "\n"
                + MARK_END
                + "\n"
            )
            print("okf: index section appended to docs/index.md")
        else:
            problems.append(
                "docs/index.md: missing okf:index markers (run with --write-index)"
            )

    if problems:
        print(f"okf: {len(problems)} problem(s):")
        for p in problems:
            print(" -", p)
        return 1
    n_related = sum(len(p.get("related") or []) for p in fm_by_rel.values())
    print(
        f"okf: OK — {len(pages)} pages, {n_related} related links, "
        "all internal links resolve, nav complete, index fresh"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))